//! The mod's own texts in the game's language, English when the language isn't covered.
//! The bridge passes the game's language code (`fr_fr`, `de_de`…) every frame.

use std::sync::RwLock;

type Table = &'static [(&'static str, &'static str)];

static CURRENT: RwLock<(String, Table, Table)> = RwLock::new((String::new(), EN, ui::EN));

use crate::i18n_ui as ui;

/// Picks the table for a language code: the language part (`fr` of `fr_ca`) decides.
pub fn set_language(code: &str) {
    if CURRENT.read().map(|c| c.0 == code).unwrap_or(false) {
        return;
    }
    let lang = code.split(['_', '-']).next().unwrap_or("en").to_ascii_lowercase();
    let (table, more) = match lang.as_str() {
        "fr" => (FR, ui::FR),
        "de" => (DE, ui::DE),
        "es" => (ES, ui::ES),
        "it" => (IT, ui::IT),
        "pt" => (PT, ui::PT),
        "ru" => (RU, ui::RU),
        "uk" => (UK, ui::UK),
        "pl" => (PL, ui::PL),
        "nl" => (NL, ui::NL),
        "tr" => (TR, ui::TR),
        "zh" => (ZH, ui::ZH),
        "ja" => (JA, ui::JA),
        _ => (EN, ui::EN),
    };
    if let Ok(mut c) = CURRENT.write() {
        *c = (code.to_owned(), table, more);
    }
}

fn find(table: Table, key: &str) -> Option<&'static str> {
    table.iter().find(|(k, _)| *k == key).map(|(_, v)| *v)
}

/// The text for `key`: the current language's, else English's, else the key.
pub fn t(key: &str) -> String {
    let (table, more) = CURRENT.read().map(|c| (c.1, c.2)).unwrap_or((EN, ui::EN));
    find(table, key)
        .or_else(|| find(more, key))
        .or_else(|| find(EN, key))
        .or_else(|| find(ui::EN, key))
        .unwrap_or(key)
        .to_owned()
}

/// `t` with `{0}`, `{1}`… replaced.
pub fn tf(key: &str, args: &[&dyn std::fmt::Display]) -> String {
    let mut s = t(key);
    for (i, a) in args.iter().enumerate() {
        s = s.replace(&format!("{{{i}}}"), &a.to_string());
    }
    s
}

