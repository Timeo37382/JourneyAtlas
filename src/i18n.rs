#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_language_has_every_key() {
        for table in [EN, FR, DE, ES, IT, PT, RU, UK, PL, NL, TR, ZH, JA] {
            for k in KEYS {
                assert!(find(table, k).is_some(), "missing {k}");
            }
            assert_eq!(table.len(), KEYS.len());
        }
        for table in [ui::EN, ui::FR, ui::DE, ui::ES, ui::IT, ui::PT, ui::RU, ui::UK, ui::PL, ui::NL, ui::TR, ui::ZH, ui::JA] {
            assert_eq!(table.len(), ui::KEYS.len());
        }
    }

    #[test]
    fn falls_back_to_english() {
        set_language("xx_yy");
        assert_eq!(t("options"), "Options");
        set_language("fr_ca");
        assert_eq!(t("waypoints"), "Balises");
        assert_eq!(tf("wp_default", &[&3]), "Balise 3");
        set_language("en_us");
    }
}
